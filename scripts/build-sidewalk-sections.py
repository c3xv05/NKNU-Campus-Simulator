def slice_z(line,lo,hi):
 out=[]
 for i in range(1,len(line)):
  a,b=line[i-1:i+1];dz=b[1]-a[1];ts=[0,1]
  if dz:
   ts += [(z-a[1])/dz for z in [lo,hi] if 0<(z-a[1])/dz<1]
  ts=sorted(ts)
  for j in range(1,len(ts)):
   t,u=ts[j-1:j+1];mid=a[1]+dz*(t+u)/2
   if lo<=mid<=hi:
    p=[round(a[0]+(b[0]-a[0])*t,3),round(a[1]+dz*t,3)];q=[round(a[0]+(b[0]-a[0])*u,3),round(a[1]+dz*u,3)]
    if not out or out[-1]!=p:out.append(p)
    out.append(q)
 return out
