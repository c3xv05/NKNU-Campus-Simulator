"""Build a single continuous entrance pavement with the exact flowerbed hole."""
import json,math
from pathlib import Path
from shapely.geometry import Polygon,LineString,box
from shapely.ops import unary_union,triangulate
from shapely import constrained_delaunay_triangles
root=Path(__file__).resolve().parents[1];c=json.loads((root/'data/campus.json').read_text());bed=Polygon(c['flowerbed']['ring'])
roads=[LineString(r['line']).buffer(r['width']/2,cap_style=2,join_style=1) for r in c['roads'] if r.get('entrance')]
outer=unary_union(roads+[bed.buffer(1.5)]).buffer(0)
assert outer.geom_type=='Polygon'
ring=[[round(x,4),round(z,4)] for x,z in list(outer.exterior.coords)[:-1]];hole=c['flowerbed']['ring'];paved=Polygon(ring,[hole]);assert paved.is_valid
coarse=[list(t.exterior.coords)[:3] for t in constrained_delaunay_triangles(paved).geoms];fine=[];step=1.5
w,n,e,s=paved.bounds
for row in range(math.ceil((s-n)/step)):
 for col in range(math.ceil((e-w)/step)):
  part=paved.intersection(box(w+col*step,n+row*step,w+(col+1)*step,n+(row+1)*step))
  if part.is_empty:continue
  for tri in constrained_delaunay_triangles(part).geoms:
   if tri.area<1e-7:continue
   for x,z in list(tri.exterior.coords)[:3]:fine.extend([round(x,4),round(z,4)])
c['entranceApron'].update(ring=ring,holes=[hole],footprints=[[[round(x,4),round(z,4)] for x,z in tri] for tri in coarse],meshStep=step)
(root/'data/campus.json').write_text(json.dumps(c,ensure_ascii=False,separators=(',',':')))
(root/'data/entrance-mesh.js').write_text('// Generated by scripts/build-entrance-apron.py. Exact shared flowerbed boundary; X/Z triangles.\nexport const entranceMesh='+json.dumps(fine,separators=(',',':'))+';\n')
print('Entrance pavement',round(paved.area,2),'m²;',len(coarse),'cutout triangles;',len(fine)//6,'render triangles')
