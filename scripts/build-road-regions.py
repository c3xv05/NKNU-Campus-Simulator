"""Developer-only build step: pip install shapely==2.1.2. No runtime geometry dependency."""
import json,math,hashlib
from road_shapes import motor_shape
from pathlib import Path
from shapely.geometry import Polygon,LineString,Point
from shapely.ops import unary_union
root=Path(__file__).resolve().parents[1];c=json.loads((root/'data/campus.json').read_text());tags=json.loads((root/'data/road-tags.json').read_text())
campus=Polygon(c['boundary']).buffer(0);roads=[r for r in c['roads'] if r['width']>2.5]
pavement=motor_shape(fillets=True);land=campus.difference(pavement)
regions=[p for p in land.geoms if p.area>100];regions.sort(key=lambda p:(-p.representative_point().y,p.representative_point().x))
def ring(points):return [[round(x,3),round(y,3)] for x,y in list(points)[:-1]]
places=[p for p in c['places'] if p.get('name')];result=[]
for i,p in enumerate(regions):
 label=p.representative_point();nearest=sorted(places,key=lambda a:Polygon(a['ring']).distance(label))[:2]
 nearroads=[r for r in roads if p.boundary.distance(LineString(r['line']))<r['width']/2+.15]
 names=list(dict.fromkeys(tags.get(str(r['osm']),{}).get('name','未命名道路') for r in nearroads))
 if p.area<800 and p.distance(Polygon(c['flowerbed']['ring']))<1:name='大門水滴花圃'
 else:name='、'.join(a['name'] for a in nearest)+'周邊'
 result.append(dict(id=f'R{i+1:02}',name=name,ring=ring(p.exterior.coords),holes=[ring(h.coords) for h in p.interiors],label=[round(label.x,3),round(label.y,3)],area=round(p.area,2),roadIds=[r['osm'] for r in nearroads],boundaryNames=names,status='unconfirmed'))
names=['大門水滴花圃','校門內中央長形空地','清心路南側與東南坡地','大門西側至宿舍區坡地','圖資大樓與中央坡地','霽遠樓北側小街廓','高斯大樓南側小街廓','高斯與生科教學街廓','致理、寰宇與科技西側街廓','生科東側球場與運動設施區','校區東北外圍坡地','操場、燕窩與科技東側街廓']
if len(result)==len(names):
 for region,name in zip(result,names):region['name']=name
revision='rr-'+hashlib.sha256(json.dumps([c['roads'],c['entranceApron']['ring'],c.get('pavedAreas',[])+c.get('junctionFillets',[])],sort_keys=True).encode()).hexdigest()[:12]
text='// Generated by scripts/build-road-regions.py; boundaries follow pavement edges and campus perimeter.\nexport const roadRegions='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\nexport const roadRegionRevision='+json.dumps(revision)+';\n'
(root/'data/road-regions.js').write_text(text)
print('Generated',len(result),'road-bounded regions; ignored tiny junction fragments:',round(sum(p.area for p in land.geoms if p.area<=100),3),'m²')
for r in result:print(r['id'],r['name'],r['boundaryNames'])
